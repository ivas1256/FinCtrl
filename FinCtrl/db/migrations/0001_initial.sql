-- Baseline PostgreSQL: структура БД FinCtrl по состоянию на 2026-11-15.
-- Итоговая схема после миграций 0001-0006 прежней истории на SQL Server (архив — db/migrations-mssql/);
-- 0007 (только данные) в baseline не входит.
-- Накатывается через psql, например:
--   psql -h localhost -p 5433 -U finctrl -d finctrl_db_dev2 -f db/migrations/0001_initial.sql
-- Идемпотентен: повторный запуск ничего не меняет.
-- Имена без кавычек: PostgreSQL приводит их к нижнему регистру, Dapper маппит без учёта регистра.

CREATE TABLE IF NOT EXISTS Categories
(
    CategoryId                  integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CategoryName                text         NULL,
    CreatedAt                   timestamp    NOT NULL,
    LastUpdatedAt               timestamp    NULL,
    ParentCategoryCategoryId    integer      NULL,
    IsOnlyIncome                boolean      NOT NULL DEFAULT false,
    OrderIndex                  integer      NOT NULL DEFAULT 0,
    Color                       varchar(7)   NOT NULL DEFAULT '#808080',
    CONSTRAINT PK_Categories PRIMARY KEY (CategoryId),
    CONSTRAINT FK_Categories_Categories_ParentCategoryCategoryId
        FOREIGN KEY (ParentCategoryCategoryId) REFERENCES Categories (CategoryId)
);

CREATE INDEX IF NOT EXISTS IX_Categories_ParentCategoryCategoryId ON Categories (ParentCategoryCategoryId);

CREATE TABLE IF NOT EXISTS PaymentSources
(
    PaymentSourceId     integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PaymentSourceName   text          NULL,
    CategoryId          integer       NULL,
    CreatedAt           timestamp     NOT NULL,
    LastUpdatedAt       timestamp     NULL,
    Description         text          NULL,
    Classification      varchar(200)  NULL,
    IsAiClassified      boolean       NOT NULL DEFAULT false,
    CONSTRAINT PK_PaymentSources PRIMARY KEY (PaymentSourceId),
    CONSTRAINT FK_PaymentSources_Categories_CategoryId
        FOREIGN KEY (CategoryId) REFERENCES Categories (CategoryId)
);

CREATE INDEX IF NOT EXISTS IX_PaymentSources_CategoryId ON PaymentSources (CategoryId);

-- Номер счёта уникален (счета без номера допускаются в любом количестве), название — нет.
CREATE TABLE IF NOT EXISTS Accounts
(
    AccountId           integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ExcelAccountName    varchar(255)  NOT NULL,
    DisplayName         varchar(255)  NOT NULL,
    CreatedAt           timestamp     NOT NULL,
    LastUpdatedAt       timestamp     NULL,
    IsSavings           boolean       NOT NULL DEFAULT false,
    AccountNumber       varchar(50)   NULL,
    CONSTRAINT PK_Accounts PRIMARY KEY (AccountId)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_Accounts_AccountNumber ON Accounts (AccountNumber)
    WHERE AccountNumber IS NOT NULL;

CREATE TABLE IF NOT EXISTS Payments
(
    PaymentId                   integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PaymentType                 integer         NOT NULL,
    PaymentSum                  numeric(18, 2)  NOT NULL,
    PaymentDate                 timestamp       NOT NULL,
    PaymentSourceId             integer         NULL,
    PaymentCategoryCategoryId   integer         NULL,
    PaymentDescription          text            NULL,
    CreatedAt                   timestamp       NOT NULL,
    LastUpdatedAt               timestamp       NULL,
    IsDeleted                   boolean         NOT NULL DEFAULT false,
    ExcludeFromStats            boolean         NOT NULL DEFAULT false,
    AccountId                   integer         NULL,
    CONSTRAINT PK_Payments PRIMARY KEY (PaymentId),
    CONSTRAINT FK_Payments_Categories_PaymentCategoryCategoryId
        FOREIGN KEY (PaymentCategoryCategoryId) REFERENCES Categories (CategoryId),
    CONSTRAINT FK_Payments_PaymentSources_PaymentSourceId
        FOREIGN KEY (PaymentSourceId) REFERENCES PaymentSources (PaymentSourceId),
    CONSTRAINT FK_Payments_Accounts_AccountId
        FOREIGN KEY (AccountId) REFERENCES Accounts (AccountId)
);

CREATE INDEX IF NOT EXISTS IX_Payments_Date_Deleted ON Payments (PaymentDate, IsDeleted);
CREATE INDEX IF NOT EXISTS IX_Payments_PaymentCategoryCategoryId ON Payments (PaymentCategoryCategoryId);
CREATE INDEX IF NOT EXISTS IX_Payments_PaymentSourceId ON Payments (PaymentSourceId);
CREATE INDEX IF NOT EXISTS IX_Payments_SourceId ON Payments (PaymentSourceId) WHERE IsDeleted = false;
CREATE INDEX IF NOT EXISTS IX_Payments_AccountId ON Payments (AccountId);

-- Защита от дублей «счёт + дата + сумма»: операции без счёта и мягко удалённые в индекс не входят
-- (удалённая операция не должна блокировать повторный импорт той же строки).
CREATE UNIQUE INDEX IF NOT EXISTS UQ_Payments_Account_Date_Sum
    ON Payments (AccountId, PaymentDate, PaymentSum)
    WHERE AccountId IS NOT NULL AND IsDeleted = false;

-- Теги. Каскадного удаления нет: приложение само чистит PaymentTags перед удалением тега.
CREATE TABLE IF NOT EXISTS Tags
(
    TagId           integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    TagName         varchar(255)  NOT NULL,
    CreatedAt       timestamp     NOT NULL,
    LastUpdatedAt   timestamp     NULL,
    CONSTRAINT PK_Tags PRIMARY KEY (TagId)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_Tags_TagName ON Tags (TagName);

CREATE TABLE IF NOT EXISTS PaymentTags
(
    PaymentId   integer NOT NULL,
    TagId       integer NOT NULL,
    CONSTRAINT PK_PaymentTags PRIMARY KEY (PaymentId, TagId),
    CONSTRAINT FK_PaymentTags_Payments FOREIGN KEY (PaymentId) REFERENCES Payments (PaymentId),
    CONSTRAINT FK_PaymentTags_Tags FOREIGN KEY (TagId) REFERENCES Tags (TagId)
);

CREATE INDEX IF NOT EXISTS IX_PaymentTags_TagId ON PaymentTags (TagId);

-- Переводы между своими счетами: OutPaymentId — списание, InPaymentId — поступление (NULL — вторая сторона
-- не указана). Каскадного удаления нет.
CREATE TABLE IF NOT EXISTS Transfers
(
    TransferId      integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    OutPaymentId    integer     NOT NULL,
    InPaymentId     integer     NULL,
    CreatedAt       timestamp   NOT NULL,
    CONSTRAINT PK_Transfers PRIMARY KEY (TransferId),
    CONSTRAINT FK_Transfers_Payments_OutPaymentId
        FOREIGN KEY (OutPaymentId) REFERENCES Payments (PaymentId),
    CONSTRAINT FK_Transfers_Payments_InPaymentId
        FOREIGN KEY (InPaymentId) REFERENCES Payments (PaymentId)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_Transfers_OutPaymentId ON Transfers (OutPaymentId);

-- Частичный индекс: переводов без второй стороны (InPaymentId IS NULL) может быть много.
CREATE UNIQUE INDEX IF NOT EXISTS UQ_Transfers_InPaymentId ON Transfers (InPaymentId)
    WHERE InPaymentId IS NOT NULL;
